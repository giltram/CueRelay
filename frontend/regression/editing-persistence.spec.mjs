import { test, expect, fixtures, button, rows, text, menu, openWorkspace, verifyVideo, readProject, saveDocument } from './helpers.mjs';

const main = page => page.locator('main.editor-workbench');
const rowText = (page, value) => rows(page).filter({ has: page.locator('.cue-text', { hasText: new RegExp(`^${value}$`) }) });
const seek = async (page, seconds) => {
  await page.locator('video').evaluate((video, time) => { video.pause(); video.currentTime = time; }, seconds);
  await expect.poll(() => page.locator('video').evaluate(video => !video.seeking && video.currentTime)).toBe(seconds);
};

test('editing clipboard cut paste and field overwrite explicitly save and reload', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await openWorkspace(page);
  const original = await readProject(page);
  await menu(page, rowText(page, '甲'), '复制字幕行');
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain(',,甲');
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  expect(copied).toContain('Default,译者,0010,0020,0030,,甲');
  expect(await readProject(page)).toEqual(original);
  await menu(page, rowText(page, '乙'), '剪切字幕行');
  await expect(rows(page)).toHaveCount(2);
  const cut = await page.evaluate(() => navigator.clipboard.readText());
  expect(cut).toContain(',,乙');
  await rowText(page, '丙').click(); await main(page).focus(); await page.keyboard.press('Control+v');
  await expect(rows(page)).toHaveCount(3);
  await expect(rowText(page, '乙')).toHaveCount(1);
  await page.evaluate(value => navigator.clipboard.writeText(value), copied);
  await main(page).focus(); await page.keyboard.press('Control+v');
  await expect(rows(page)).toHaveCount(4);
  const targetId = await rows(page).and(page.locator('[aria-selected="true"]')).getAttribute('data-cue-id');
  await expect(text(page)).toHaveValue('甲');
  const beforeOverwrite = await rows(page).evaluateAll(elements => elements.map(row => ({ id: row.dataset.cueId, times: [...row.querySelectorAll('.time-cell')].map(cell => cell.textContent) })));
  await page.evaluate(() => navigator.clipboard.writeText('Dialogue: 3,0:00:07.00,0:00:07.50,Emphasis,覆盖者,0001,0002,0003,,覆盖正文'));
  await main(page).focus(); await page.keyboard.press('Control+Shift+v');
  const dialog = page.getByRole('dialog', { name: '选择字段粘贴覆盖字幕行', exact: true });
  await dialog.getByRole('checkbox', { name: '入点', exact: true }).check();
  await button(dialog, '粘贴覆盖').click();
  await expect(dialog.getByRole('alert')).toBeVisible();
  await expect(dialog.getByRole('checkbox', { name: '入点', exact: true })).toBeChecked();
  await expect(text(page)).toHaveValue('甲');
  expect(await readProject(page)).toEqual(original);
  // Select only text/style: preserve destination times and identity/ASS fields.
  await dialog.getByRole('checkbox', { name: '入点', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: '样式', exact: true }).check();
  await button(dialog, '粘贴覆盖').click(); await expect(dialog).toHaveCount(0);
  await expect(text(page)).toHaveValue('覆盖正文');
  expect(await rows(page).evaluateAll(elements => elements.map(row => ({ id: row.dataset.cueId, times: [...row.querySelectorAll('.time-cell')].map(cell => cell.textContent) })))).toEqual(beforeOverwrite);
  expect(await readProject(page)).toEqual(original);
  const saved = await saveDocument(page, 1);
  const overwritten = saved.document.cues.find(cue => cue.id === targetId);
  expect(overwritten).toMatchObject({ start_ms: 0, end_ms: 2000, text: '覆盖正文', style_id: original.document.styles.find(style => style.name === 'Emphasis').id });
  expect(saved.document.cues.find(cue => cue.text === '乙').id).not.toBe(original.document.cues[1].id);
  expect(saved.document.cues.filter(cue => ['甲', '丙'].includes(cue.text))).toEqual([original.document.cues[0], original.document.cues[2]]);
  const exported = await page.request.post('/api/ass/export', { data: { document: saved.document } });
  expect(exported.status()).toBe(200);
  expect(await exported.text()).toContain('3,0:00:00.00,0:00:02.00,Emphasis,译者,0010,0020,0030,,覆盖正文');
  await page.reload(); await verifyVideo(page);
  await expect(rows(page)).toHaveCount(4);
  expect(await readProject(page)).toEqual(saved);
  await expect(rowText(page, '覆盖正文').locator('.style-cell')).toHaveText('Emphasis');
});

test('editing playhead split trim insert delete and multi styles persist', async ({ page }) => {
  await openWorkspace(page);
  const initial = await readProject(page);
  await main(page).focus(); await seek(page, 1); await page.keyboard.press('Control+p');
  await expect(page.getByRole('alert')).toContainText('含有文本的字幕请使用文本光标拆分');
  expect(await readProject(page)).toEqual(initial);
  await text(page).fill(''); await main(page).focus();
  const splitting = page.waitForResponse(r => r.url().endsWith(`${fixtures.projectPath}/split`) && r.request().method() === 'POST');
  await page.keyboard.press('Control+p');
  const response = await splitting;
  expect(response.status()).toBe(200);
  expect(response.request().postDataJSON()).toMatchObject({ revision: 1, mode: 'playhead', position: 1000 });
  await expect(rows(page)).toHaveCount(2);
  const split = await readProject(page);
  expect(split.revision).toBe(2);
  expect(split.document.cues.map(cue => [cue.start_ms, cue.end_ms, cue.text])).toEqual([[0, 1000, ''], [1000, 2000, '']]);
  await page.reload(); await verifyVideo(page);
  expect(await readProject(page)).toEqual(split);
  await seek(page, 0.2); await main(page).focus(); await page.keyboard.press('Control+b');
  await expect(rows(page).first().locator('.time-cell')).toHaveText(['0:00:00.20', '0:00:01.00']);
  await seek(page, 0.8); await page.keyboard.press('Control+m');
  await expect(rows(page).first().locator('.time-cell')).toHaveText(['0:00:00.20', '0:00:00.80']);
  await menu(page, rows(page).first(), '在当前行后插入字幕'); await expect(rows(page)).toHaveCount(3);
  await text(page).fill('插入保留');
  const insertedId = await rows(page).nth(1).getAttribute('data-cue-id');
  await menu(page, rows(page).first(), '在当前行后插入字幕'); await expect(rows(page)).toHaveCount(4);
  await expect(page.getByRole('textbox', { name: '入点', exact: true })).toHaveValue('0:00:00.80');
  await expect(page.getByRole('textbox', { name: '出点', exact: true })).toHaveValue('0:00:00.80');
  await button(page, '删除选中行').click(); await expect(rows(page)).toHaveCount(3);
  await button(page, '选择第 1 行').click(); await button(page, '选择第 3 行').click({ modifiers: ['ControlOrMeta'] });
  const selectedIds = await rows(page).and(page.locator('[aria-selected="true"]')).evaluateAll(elements => elements.map(row => row.dataset.cueId));
  await page.getByRole('textbox', { name: '入点', exact: true }).fill('0:');
  const emphasis = split.document.styles.find(style => style.name === 'Emphasis').id;
  await page.getByLabel('字幕样式', { exact: true }).selectOption(emphasis);
  expect(await rows(page).and(page.locator('[aria-selected="true"]')).evaluateAll(elements => elements.map(row => row.dataset.cueId))).toEqual(selectedIds);
  await expect(page.getByRole('textbox', { name: '入点', exact: true })).toHaveValue('0:');
  await expect(rows(page).locator('.style-cell')).toHaveText(['Emphasis', 'Default', 'Emphasis']);
  expect(await readProject(page)).toEqual(split); // No structural/style autosave.
  await page.getByRole('textbox', { name: '入点', exact: true }).fill('0:00:01.00');
  const saved = await saveDocument(page, 2);
  expect(saved.document.cues.map(cue => [cue.start_ms, cue.end_ms, cue.text])).toEqual([[200, 800, ''], [800, 1000, '插入保留'], [1000, 2000, '']]);
  expect(saved.document.cues.find(cue => cue.id === insertedId).style_id).toBe(split.document.styles[0].id);
  expect(saved.document.styles).toEqual(split.document.styles);
  await page.reload(); await verifyVideo(page);
  await expect(rows(page)).toHaveCount(3);
  await expect(rows(page).locator('.style-cell')).toHaveText(['Emphasis', 'Default', 'Emphasis']);
  expect(await readProject(page)).toEqual(saved);
});

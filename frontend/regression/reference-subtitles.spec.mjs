test('project reference stale reads cannot override revocation and local navigation hides project reference', async ({ page, browser }) => {
  const adminContext = await browser.newContext({ locale: 'zh-CN', baseURL: 'http://127.0.0.1:5199' });
  const admin = await adminContext.newPage();
  await login(admin, fixtures.workspacePath.replace('/workspace', '/settings'), fixtures.organizer);
  expect((await request(adminContext, fixtures.projectPath + '/reference', 'PUT', { version: 1, source })).status()).toBe(200);
  await login(page, fixtures.workspacePath);
  await verifyVideo(page);
  await expect(panel(page).locator('[data-reference-current]')).toHaveCount(3);
  const video = await page.locator('video').elementHandle();
  await text(page).fill('撤权保留正文');
  let releaseOld, captured;
  const oldCaptured = new Promise(resolve => { captured = resolve; });
  const hold = new Promise(resolve => { releaseOld = resolve; });
  let intercept = true;
  await page.route(`**${fixtures.projectPath}`, async route => {
    if (route.request().method() !== 'GET' || !intercept) return route.continue();
    intercept = false;
    const response = await route.fetch(); captured(); await hold;
    await route.fulfill({ response });
  });
  await page.evaluate(() => window.dispatchEvent(new Event('focus'))); await oldCaptured;
  const orgPath = fixtures.projectPath.split('/projects/')[0];
  const members = await (await request(adminContext, orgPath + '/members')).json();
  const membership = members.members.find(value => value.username === fixtures.username);
  expect(membership).toBeTruthy();
  expect((await request(adminContext, orgPath + '/members/' + membership.id, 'DELETE', {})).status()).toBe(200);
  const denied = page.waitForResponse(r => new URL(r.url()).pathname === fixtures.projectPath && r.status() === 403);
  await page.evaluate(() => window.dispatchEvent(new Event('focus'))); await denied;
  await expect(panel(page)).toHaveCount(0);
  await expect(text(page)).toHaveValue('撤权保留正文');
  const returned = page.waitForResponse(r => new URL(r.url()).pathname === fixtures.projectPath && r.status() === 200);
  releaseOld(); await returned;
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await expect(panel(page)).toHaveCount(0);
  expect(await video.evaluate(node => node.isConnected)).toBe(true);
  expect((await request(adminContext, orgPath + '/members', 'POST', { username: fixtures.username })).status()).toBe(200);
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(panel(page).locator('[data-reference-current]')).toHaveCount(3);
  await expect(text(page)).toHaveValue('撤权保留正文');
  await page.locator('main.editor-workbench').focus(); await page.keyboard.press('Control+z');
  await expect(text(page)).toHaveValue('甲乙');
  // Same-document departure to local editor has no project reference.
  await page.getByRole('link', { name: 'CueRelay', exact: true }).click();
  const local = page.getByRole('link', { name: '本地工作区', exact: true });
  const localHref = await local.getAttribute('href');
  await page.evaluate(path => { history.pushState(null, '', path); window.dispatchEvent(new PopStateEvent('popstate')); }, localHref);
  await expect(page.locator('main.editor-workbench:visible')).toHaveCount(1);
  await expect(page.locator('main.editor-workbench:visible [data-reference-subtitles]')).toHaveCount(0);
  await adminContext.close();
});

import { test, expect, fixtures, button, rows, text, login, request, readProject, verifyVideo } from './helpers.mjs';
const file = (source, name = 'reference.srt') => ({ name, mimeType: 'text/plain', buffer: Buffer.from(source) });
const source = '9\n00:00:03,001 --> 00:00:04,234\n后文\n\n2\n00:00:00,001 --> 00:00:00,600\n<b>参考甲</b> &lt;script&gt;\n\n3\n00:00:00,600 --> 00:00:01,200\n参考乙\n\n4\n00:00:01,200 --> 00:00:02,000\n参考丙';
const panel = page => page.locator('[data-reference-subtitles]');
const upload = async (settings, value) => {
  await settings.getByLabel('选择参考 SRT', { exact: true }).setInputFiles(file(value));
  const written = settings.waitForResponse(r => r.url().endsWith('/reference') && r.request().method() === 'PUT');
  await button(settings, '上传参考字幕').click();
  return written;
};

test('project reference settings refresh preserves subtitle draft media selection history and follows real playback clocks', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await login(page, fixtures.workspacePath, fixtures.organizer);
  await verifyVideo(page);
  await expect(panel(page)).toHaveCount(0);
  await text(page).fill('未保存的正式正文');
  const selectedId = await rows(page).first().getAttribute('data-cue-id');
  const before = await readProject(page);
  const video = await page.locator('video').elementHandle();
  await expect(page.locator('.ass-preview-status')).toHaveAttribute('data-phase', 'ready');
  const preview = await page.locator('.ass-preview-canvas').elementHandle();
  const videoSize = await page.locator('.video-stage').boundingBox();
  const settings = await context.newPage();
  await settings.goto(fixtures.workspacePath.replace('/workspace', '/settings'));
  await expect(settings.getByText('尚无参考字幕。', { exact: true })).toBeVisible();
  await upload(settings, source);
  await expect(settings.getByRole('status')).toContainText('参考字幕已保存');
  const stored = await readProject(page);
  expect(stored.revision).toBe(before.revision); expect(stored.document).toEqual(before.document);
  expect(stored.reference.cues[0].start_ms).toBe(3001);
  await page.bringToFront();
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(panel(page).locator('[data-reference-current]')).toHaveText(['参考甲 <script>', '参考乙', '参考丙']);
  await expect(text(page)).toHaveValue('未保存的正式正文');
  expect(await video.evaluate(node => node === document.querySelector('video'))).toBe(true);
  expect(await preview.evaluate(node => node === document.querySelector('.ass-preview-canvas'))).toBe(true);
  expect(await page.locator('.video-stage').boundingBox()).toEqual(videoSize);
  expect(await rows(page).first().getAttribute('data-cue-id')).toBe(selectedId);
  await expect(panel(page).locator('script')).toHaveCount(0);
  // A real DOM selection can be copied with normal browser shortcuts.
  await panel(page).locator('.reference-content').focus();
  await panel(page).locator('[data-reference-current]').first().evaluate(node => {
    const range = document.createRange(); range.selectNodeContents(node);
    const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range);
  });
  await page.keyboard.press('Meta+c');
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('参考甲 <script>');
  await text(page).focus();
  await button(panel(page), '参考字幕 · 收起').click();
  await expect(text(page)).toBeFocused();
  await expect(panel(page).locator('.reference-content')).toHaveCount(0);
  await button(panel(page), '参考字幕 · 展开').click();
  // Set playback at a known point through the actual video clock.
  await page.locator('video').evaluate(video => { video.currentTime = 3.15; return video.play(); });
  await expect(panel(page).locator('[data-reference-current]')).toHaveText(['后文']);
  await page.locator('video').evaluate(video => video.pause());
  await expect(panel(page).locator('[data-reference-current]')).toHaveText(['参考甲 <script>', '参考乙', '参考丙']);
  // Independent audition leaves video at 3.15+ but runs through the selected 0–2s range.
  const videoTime = await video.evaluate(node => node.currentTime);
  await page.locator('main.editor-workbench').focus();
  await page.keyboard.press('Space');
  await expect.poll(() => panel(page).locator('[data-reference-current]').allTextContents()).toEqual(['参考乙']);
  expect(Math.abs(await video.evaluate(node => node.currentTime) - videoTime)).toBeLessThan(.1);
  await expect(panel(page).locator('[data-reference-current]')).toHaveText(['参考甲 <script>', '参考乙', '参考丙']);
  // Failed replacement and stale reference CAS retain both old reference and settings inputs.
  await settings.bringToFront();
  await settings.getByLabel('项目名称', { exact: true }).fill('保留设置草稿');
  await upload(settings, 'bad');
  await expect(settings.getByRole('alert')).toContainText('字幕块');
  await expect(settings.getByLabel('项目名称', { exact: true })).toHaveValue('保留设置草稿');
  expect((await readProject(page)).reference).toEqual(stored.reference);
  await upload(settings, source.replace('参考甲', '新版参考'));
  await expect(settings.getByRole('status')).toContainText('参考字幕已保存');
  await page.bringToFront(); await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(panel(page).locator('[data-reference-current]').first()).toHaveText('新版参考 <script>');
  await expect(text(page)).toHaveValue('未保存的正式正文');
  await page.locator('main.editor-workbench').focus(); await page.keyboard.press('Control+z');
  await expect(text(page)).toHaveValue('甲乙');
  await page.keyboard.press('Control+Shift+z'); await expect(text(page)).toHaveValue('未保存的正式正文');
  // Long preceding context scrolls internally to reveal the current match.
  await settings.bringToFront();
  expect((await upload(settings, source.replace('参考丙', '很长的上下文'.repeat(1000)))).status()).toBe(200);
  await page.bringToFront(); await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(panel(page).locator('[data-reference-current]').last()).toContainText('很长的上下文');
  await page.locator('video').evaluate(video => { video.currentTime = 3.15; return video.play(); });
  await expect(panel(page).locator('[data-reference-current]')).toHaveText(['后文']);
  await expect.poll(() => panel(page).locator('.reference-content').evaluate(node => node.scrollTop)).toBeGreaterThan(100);
  expect(await panel(page).evaluate(node => {
    const current = node.querySelector('[data-reference-current]').getBoundingClientRect();
    const scroll = node.querySelector('.reference-content').getBoundingClientRect();
    return current.top >= scroll.top && current.bottom <= scroll.bottom;
  })).toBe(true);
  await page.locator('video').evaluate(video => video.pause());
  await panel(page).locator('.reference-content').evaluate(node => { node.scrollTop = 80; });
  const observed = page.waitForResponse(r => new URL(r.url()).pathname === fixtures.projectPath && r.request().method() === 'GET');
  await page.evaluate(() => window.dispatchEvent(new Event('focus'))); expect((await observed).status()).toBe(200);
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  expect(await panel(page).locator('.reference-content').evaluate(node => node.scrollTop)).toBe(80);
  // Stable reference height; existing divider still resizes the same video node.
  const height = await panel(page).evaluate(node => node.getBoundingClientRect().height);
  await page.getByRole('separator', { name: '调整视频区域大小', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  expect(await video.evaluate(node => node === document.querySelector('video'))).toBe(true);
  await page.setViewportSize({ width: 1100, height: 620 });
  await expect(panel(page)).toBeVisible();
  expect(await panel(page).evaluate(node => node.getBoundingClientRect().height)).toBe(height);
  await page.setViewportSize({ width: 700, height: 700 });
  await text(page).scrollIntoViewIfNeeded(); await expect(text(page)).toBeEditable();
  await page.screenshot({ path: test.info().outputPath('reference-narrow.png') });
  await settings.bringToFront();
  const cleared = settings.waitForResponse(r => r.url().endsWith('/reference') && r.request().method() === 'PUT');
  await button(settings, '清除参考字幕').click();
  expect((await cleared).status()).toBe(200);
  await expect(settings.getByText('尚无参考字幕。', { exact: true })).toBeVisible();
  await page.bringToFront(); await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(panel(page)).toHaveCount(0);
  await expect(text(page)).toHaveValue('未保存的正式正文');
  await button(page, '保存项目').scrollIntoViewIfNeeded(); await button(page, '保存项目').click();
  await expect(button(page, '保存项目')).toBeDisabled();
  const saved = await readProject(page);
  expect(saved.document.cues[0].text).toBe('未保存的正式正文'); expect(saved.revision).toBe(before.revision + 1);
  expect(saved.reference.cues).toBeNull();
 });


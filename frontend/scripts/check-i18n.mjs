import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { flattenCatalog, validateCatalogs } from '../build/i18n-validation.ts';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const languages = JSON.parse(readFileSync(resolve(root, 'shared/languages.json'), 'utf8'));
if (Object.values(languages).filter(language => language.fallback).length !== 1) throw new Error('Exactly one fallback language is required');
const catalogs = Object.fromEntries(Object.keys(languages).map(language => [language,
  Object.fromEntries(readdirSync(resolve(root, `frontend/src/i18n/locales/${language}`)).filter(file => file.endsWith('.json')).map(file => [file.replace(/\.json$/, ''), JSON.parse(readFileSync(resolve(root, `frontend/src/i18n/locales/${language}/${file}`), 'utf8'))]))]));
const errors = validateCatalogs(catalogs, 'en');
for (const [id, language] of Object.entries(languages)) {
  if (!readFileSync(resolve(root, `frontend/src/handbook-ui/${language.handbook}`), 'utf8')) errors.push(`Missing handbook: ${id}`);
}
const keys = Object.keys(flattenCatalog(catalogs.en)).sort();
const generated = '/** Generated from the English catalog by npm run i18n:types. Do not edit. */\nexport type MessageKey =\n'
  + keys.map(key => `  | ${JSON.stringify(key)}`).join('\n') + ';\n';
const namespaces = Object.keys(catalogs.en).sort();
const resourceTypes = '/** Generated by npm run i18n:types. */\n' + namespaces.map(name => `import type ${name} from './locales/en/${name}.json';`).join('\n') + '\nexport interface TranslationResources {\n' + namespaces.map(name => `  ${name}: typeof ${name};`).join('\n') + '\n}\n';
const resourceTarget = resolve(root, 'frontend/src/i18n/resource-types.ts');
if (process.argv.includes('--write-types')) writeFileSync(resourceTarget, resourceTypes);
else if (readFileSync(resourceTarget, 'utf8') !== resourceTypes) errors.push('Resource types are stale. Run npm run i18n:types.');
const target = resolve(root, 'frontend/src/contracts/message-keys.ts');
if (process.argv.includes('--write-types')) writeFileSync(target, generated);
else if (readFileSync(target, 'utf8') !== generated) errors.push('Message key types are stale. Run npm run i18n:types.');
function files(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => entry.isDirectory()
    ? ['migrations', '__pycache__'].includes(entry.name) ? [] : files(resolve(directory, entry.name))
    : entry.name.endsWith('.py') && !entry.name.startsWith('test') ? [resolve(directory, entry.name)] : []);
}
for (const file of files(resolve(root, 'backend'))) {
  for (const match of readFileSync(file, 'utf8').matchAll(/localized\(['"]([^'"]+)['"]/g)) {
    if (!keys.includes(match[1])) errors.push(`Unknown backend message ${match[1]} in ${file}`);
  }
}
if (errors.length) throw new Error(errors.join('\n'));
console.log(`Validated ${Object.keys(catalogs).join(', ')}: ${keys.length} resource entries; semantic keys, placeholders, plural categories, backend reasons and generated key types.`);
